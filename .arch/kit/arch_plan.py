"""arch_plan: the plan-time stage (SPEC-CHIEF-ARCHITECT section 5.4).

Before code exists the architect answers: where does this go, what already implements it, which dependency must never appear.
`prescan` is deterministic (canon capabilities and modules whose names overlap the feature's nouns). The agent then reads those
modules and fills .arch/plan.json; `validate` checks the schema and that every reuse reference exists. A founder card is created
only when a new shared module or an exception is needed.
"""

import re
import zlib
from pathlib import Path

import arch_config as ac

REQUIRED = {
    "place": list,
    "reuse": list,
    "new_shared_modules": list,
    "touches_legacy": bool,
    "exceptions_needed": list,
}
TOOLS = Path(__file__).resolve().parent
ARC_BLOCK = """
## ARCH (generated by arch-kit plan)
- [ ] ARC-01: architecture check passes [VERIFY: python3 {t}/arch_kit.py check]
- [ ] ARC-02: deprecated usage in touched files did not increase [VERIFY: python3 {t}/arch_kit.py check --touched]
- [ ] ARC-03: files created are within the plan's place list or carry an exception id [VERIFY: python3 {t}/arch_kit.py check --places]
- [ ] ARC-04: policy files unchanged unless a decision id is cited [VERIFY: python3 {t}/arch_kit.py check --policy]
"""


def words(text):
    return {
        w
        for w in re.findall(r"[a-z]{3,}", text.lower())
        if w not in {"the", "and", "for", "with", "new", "feature", "add", "use"}
    }


def prescan(root, canon, feature, nouns=()):
    """Capabilities and modules that overlap the feature's nouns (so the builder is shown what already exists)."""
    ws = words(feature) | {n.lower() for n in nouns}
    caps = []
    for cap, spec in (canon.get("capabilities") or {}).items():
        canonical = spec.get("canonical")
        canonical = [canonical] if isinstance(canonical, str) else (canonical or [])
        hay = (
            words(cap.replace(".", " "))
            | words(" ".join(canonical))
            | words(spec.get("note", ""))
        )
        if ws & hay:
            caps.append(
                {
                    "capability": cap,
                    "canonical": canonical,
                    "bans": spec.get("bans", []),
                }
            )
    mods = []
    for f in ac.source_files(root, canon):
        stem = Path(f).stem.lower()
        parts = set(re.findall(r"[a-z]{3,}", f.lower().replace("/", " ")))
        if ws & (parts | {stem}):
            mods.append(f)
    return {"capabilities": caps, "candidate_files": sorted(mods)[:40]}


def skeleton(root, canon, feature, nouns=()):
    return {
        "feature": feature,
        "candidates": prescan(root, canon, feature, nouns),
        "place": [],
        "reuse": [],
        "new_shared_modules": [],
        "touches_legacy": None,
        "exceptions_needed": [],
        "note": "The builder must open the candidate modules, then fill place, reuse, new_shared_modules, touches_legacy and exceptions_needed.",
    }


def write_plan(root, canon, feature, nouns=(), force=False):
    p = ac.arch_path(root, "plan.json")
    if p.is_file() and not force:
        return p, False
    ac.save_json(p, skeleton(root, canon, feature, nouns))
    return p, True


def validate(root, plan_path=None):
    """(errors, needs_card)."""
    plan = ac.load_json(plan_path or ac.arch_path(root, "plan.json"))
    canon = ac.load_canon(root) or {}
    if plan is None:
        return ["no architecture plan: run arch-kit plan"], False
    errs = []
    for k, t in REQUIRED.items():
        if not isinstance(plan.get(k), t):
            errs.append(
                f"plan.{k} must be a {t.__name__}"
                + (" (true or false)" if t is bool else "")
            )
    if errs:
        return errs, False
    if not plan["place"] or not all(
        isinstance(x, str) and x.strip() for x in plan["place"]
    ):
        errs.append("plan.place must list where new files go (path globs)")
    caps = set((canon.get("capabilities") or {}).keys())
    files = set(ac.list_files(root, canon.get("ignore", [])))
    for r in plan["reuse"]:
        if (
            r not in caps
            and r not in files
            and not any(f.startswith(str(r).rstrip("/") + "/") for f in files)
        ):
            errs.append(
                f"plan.reuse '{r}' is neither a capability nor an existing path"
            )
    needs = bool(plan["new_shared_modules"] or plan["exceptions_needed"])
    return errs, needs


def spec_block(spec_path):
    """Append the standard ARCH block to a spec if it is missing. Returns True if it changed the file."""
    p = Path(spec_path)
    text = p.read_text()
    if "## ARCH (generated by arch-kit plan)" in text:
        return False
    p.write_text(text.rstrip("\n") + "\n" + ARC_BLOCK.format(t=TOOLS))
    return True


def founder_card(root, plan):
    """Decisions-page card for new shared modules / exceptions. Returns the file path."""
    items = plan["new_shared_modules"] + plan["exceptions_needed"]
    name = f"arch-plan-{Path(root).name}-{zlib.crc32(plan['feature'].encode()) % 10**6}.decisions.json"
    card = {
        "title": f"Architecture plan: {plan['feature'][:60]}",
        "status": "pending",
        "budget": 5,
        "context": "The architect's plan needs your choice before building starts.",
        "basis_unstated": True,
        "scope": {
            "will_build": "The feature, using the existing modules wherever possible.",
            "wont_build": "A second way to do something that already has one.",
            "done_when": "You have said whether the proposed new shared module is justified.",
        },
        "decisions": [
            {
                "id": "d1",
                "kind": "question",
                "impact": "med",
                "title": "A new shared module is proposed",
                "plain_english": (
                    "The plan wants to add something new and shared: "
                    + ", ".join(map(str, items))
                    + ". The risk is a second way to do something that may already exist. Approving allows it once; otherwise the existing module is used or improved."
                )[:880],
                "why_it_matters": "Each extra shared module is another thing to maintain and another place for logic to drift.",
                "evidence": "Raised by arch-kit plan; see .arch/plan.json.",
                "if_unsure": "Say no and reuse or extend the existing module.",
                "reversible": "Yes. It can be merged back before release.",
                "options": [
                    {
                        "id": "a",
                        "label": "Reuse or extend the existing module",
                        "consequence": "No new shared code; the agent adapts the existing module.",
                        "recommended": True,
                    },
                    {
                        "id": "b",
                        "label": "Allow the new shared module",
                        "consequence": "A new module is created; the plan records why.",
                    },
                    {"id": "other", "label": "Other"},
                ],
            }
        ],
    }
    p = ac.decisions_dir() / name
    ac.save_json(p, card)
    return p
