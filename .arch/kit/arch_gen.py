"""arch_gen: derive files from canon.yaml so the architecture documentation can never go stale (section 5.2).

Writes the generated block of docs/ARCHITECTURE.md (between markers; the hand-written intent stays), plus
dependency-cruiser and ESLint configuration derived from the canon, for repos that also want to run those tools.
"""

import json
import posixpath
from pathlib import Path

import arch_config as ac

BEGIN, END = "<!-- arch:gen:start -->", "<!-- arch:gen:end -->"
HEADER = "# Architecture\n\nWrite one screen here: what this product is, the layers, and the rule for where new code goes.\n\n"


def modules(root, canon):
    """Directories (depth 1 to 2) that contain source files: the module list, without counts so it only changes when a module appears."""
    files = ac.source_files(root, canon)
    mods = set()
    for f in files:
        parts = f.split("/")[:-1]
        if parts:
            mods.add("/".join(parts[:1]))
        if len(parts) >= 2:
            mods.add("/".join(parts[:2]))
    return sorted(mods)


def generated_block(root, canon):
    caps = canon.get("capabilities") or {}
    layers = canon.get("layers") or {}
    lines = [
        BEGIN,
        "",
        "_Generated by `arch-kit gen` from `.arch/canon.yaml`. Do not edit between the markers._",
        "",
        "### One way to do each job",
        "",
        "| Capability | Canonical module | Banned elsewhere |",
        "|---|---|---|",
    ]
    for cap, spec in caps.items():
        canonical = spec.get("canonical")
        canonical = (
            ", ".join(canonical) if isinstance(canonical, list) else (canonical or "")
        )
        lines.append(
            f"| {cap} | `{canonical}` | {', '.join('`' + b + '`' for b in spec.get('bans', [])) or '-'} |"
        )
    if layers:
        lines += ["", "### Layers", ""]
        for name, pats in layers.items():
            lines.append(f"- **{name}**: " + ", ".join(f"`{p}`" for p in pats))
    lines += (
        ["", "### Modules", ""] + [f"- `{m}`" for m in modules(root, canon)] + ["", END]
    )
    return "\n".join(lines)


def current_block(text):
    if BEGIN in text and END in text:
        return text[text.index(BEGIN) : text.index(END) + len(END)]
    return None


def arch_doc(root):
    return Path(root) / "docs" / "ARCHITECTURE.md"


def is_stale(root, canon):
    p = arch_doc(root)
    if not p.is_file():
        return True
    return current_block(p.read_text()) != generated_block(root, canon)


def depcruise_config(canon):
    layers = canon.get("layers") or {}
    forbidden = []
    if layers.get("legacy"):
        forbidden.append(
            {
                "name": "no-new-to-legacy",
                "severity": "error",
                "comment": "derived from .arch/canon.yaml",
                "from": {"path": [_rx(p) for p in layers.get("new", [])] or ["^"]},
                "to": {"path": [_rx(p) for p in layers["legacy"]]},
            }
        )
    return {
        "forbidden": forbidden,
        "options": {"doNotFollow": {"path": "node_modules"}},
    }


def _rx(glob):
    return (
        "^"
        + ac.glob_re(glob).pattern.strip("^$").replace("\\(", "(").replace("\\)", ")")
        + "$"
    )


def eslint_restricted(canon):
    names = [
        b
        for spec in (canon.get("capabilities") or {}).values()
        for b in spec.get("bans", [])
        if b.isidentifier() or "/" in b and "(" not in b
    ]
    return {
        "no-restricted-imports": [
            "error",
            {
                "paths": [
                    {
                        "name": n,
                        "message": "banned by .arch/canon.yaml; use the canonical module",
                    }
                    for n in names
                ]
            },
        ]
    }


def gen(root):
    """Write the generated block and derived configs. Returns the list of files written."""
    root = Path(root)
    canon = ac.load_canon(root)
    block = generated_block(root, canon)
    doc = arch_doc(root)
    doc.parent.mkdir(parents=True, exist_ok=True)
    text = doc.read_text() if doc.is_file() else HEADER
    old = current_block(text)
    new_text = (
        text.replace(old, block) if old else text.rstrip("\n") + "\n\n" + block + "\n"
    )
    written = []
    if new_text != (doc.read_text() if doc.is_file() else None):
        doc.write_text(new_text)
        written.append(str(doc.relative_to(root)))
    gdir = ac.arch_path(root, "generated")
    gdir.mkdir(parents=True, exist_ok=True)
    for name, data in (
        ("depcruise.json", depcruise_config(canon)),
        ("eslint-restricted.json", eslint_restricted(canon)),
    ):
        p = gdir / name
        body = json.dumps(data, indent=1, sort_keys=True) + "\n"
        if not p.is_file() or p.read_text() != body:
            p.write_text(body)
            written.append(posixpath.join(ac.ARCH_DIR, "generated", name))
    import arch_lifecycle  # superseded-code index and lint bans (SPEC-SUPERSESSION)

    written += arch_lifecycle.gen(root)
    return written
